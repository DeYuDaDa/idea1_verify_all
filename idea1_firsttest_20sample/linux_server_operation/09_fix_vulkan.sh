#!/usr/bin/env bash
# Run on the Linux server. Fix only Vulkan userspace dependencies, not drivers.
source "$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)/common.sh"
print_settings
resolve_conda
env_exists || die "The thor20 environment is missing. This repair does not recreate Python environments."

check_only=false
if [[ $# -gt 1 ]]; then
  die "Usage: bash linux_server_operation/09_fix_vulkan.sh [--check-only]"
elif [[ $# -eq 1 ]]; then
  [[ "$1" == --check-only ]] || die "Unknown argument: $1"
  check_only=true
fi
[[ "$(uname -s)" == Linux ]] || die "Run this on the Linux server only."

if [[ "$check_only" == false ]]; then
  command -v apt-get >/dev/null 2>&1 || die "This repair targets Debian/Ubuntu. No system changes made: apt-get is unavailable."
  task_privilege=()
  if (( EUID != 0 )); then
    command -v sudo >/dev/null 2>&1 || die "Run as root, or use an account with sudo."
    sudo -n true || die "Passwordless sudo is unavailable. Run this script as root or with sudo, preserving your intended Conda path."
    task_privilege=(sudo -n)
  fi
  task_packages_ready=true
  for task_package in libvulkan1 vulkan-tools; do
    if ! dpkg-query -W -f='${Status}' "$task_package" 2>/dev/null | grep -qx 'install ok installed'; then
      task_packages_ready=false
    fi
  done
  if [[ "$task_packages_ready" == false ]]; then
    printf '\nInstalling libvulkan1 and vulkan-tools only. No NVIDIA kernel driver or CUDA reinstall is requested.\n'
    "${task_privilege[@]}" apt-get -o Acquire::Retries=2 -o Acquire::http::Timeout=30 -o Acquire::https::Timeout=30 update
    "${task_privilege[@]}" apt-get -o Acquire::Retries=2 -o Acquire::http::Timeout=30 -o Acquire::https::Timeout=30 \
      install -y --no-install-recommends libvulkan1 vulkan-tools
  else
    printf '\nVulkan loader and diagnostic packages are already installed.\n'
  fi
fi

printf '\nChecking the Vulkan loader from the same Conda environment as AI2-THOR:\n'
run_python -c 'import ctypes; from ctypes.util import find_library; name=find_library("vulkan"); print("find_library(vulkan):", name); assert name, "Vulkan loader is still undiscoverable; retain this log"; ctypes.CDLL(name); print("VULKAN_LOADER_LOADABLE")'

printf '\nVisible NVIDIA GPU (diagnostic; does not establish Vulkan graphics access):\n'
if command -v nvidia-smi >/dev/null 2>&1; then
  nvidia-smi --query-gpu=name,driver_version,memory.total --format=csv,noheader || true
else
  printf 'nvidia-smi is unavailable.\n'
fi

printf '\nVulkan ICD manifest paths (report only, no configuration rewrite):\n'
for task_icd_dir in /etc/vulkan/icd.d /usr/share/vulkan/icd.d /usr/local/share/vulkan/icd.d; do
  if [[ -d "$task_icd_dir" ]]; then
    find "$task_icd_dir" -maxdepth 1 -type f -name '*.json' -print
  fi
done
printf '\nRegistered Vulkan/NVIDIA graphics libraries (report only):\n'
if command -v ldconfig >/dev/null 2>&1; then
  ldconfig -p 2>/dev/null | grep -Ei 'libvulkan|libGLX_nvidia|libnvidia-(glvkspirv|eglcore|glcore)' || true
fi

command -v vulkaninfo >/dev/null 2>&1 || die "vulkaninfo is missing; install vulkan-tools or rerun without --check-only."
task_vulkan_report="${LOG_DIR%/}/${_lso_timestamp}_vulkan_summary.txt"
printf '\nChecking real Vulkan device enumeration:\n'
set +e
vulkaninfo --summary > "$task_vulkan_report" 2>&1
task_vulkan_status=$?
set -e
cat "$task_vulkan_report"
if (( task_vulkan_status != 0 )); then
  printf '\nThe loader is present, but Vulkan device enumeration failed. Do not reinstall the Python environment.\n' >&2
  printf 'In a GPU container, NVIDIA graphics/ICD libraries may need to be exposed by the container platform. No kernel drivers were installed by this script.\n' >&2
  die "Return this stage log and $task_vulkan_report for the next diagnosis."
fi
if ! grep -Eiq 'vendorID[[:space:]]*=[[:space:]]*0x10de|deviceName[[:space:]]*=[[:space:]]*NVIDIA' "$task_vulkan_report"; then
  printf '\nNo NVIDIA Vulkan device was found. Successful nvidia-smi alone is insufficient; llvmpipe/lavapipe is CPU rendering.\n' >&2
  die "Inspect the ICD/container graphics configuration before launching the NVIDIA CloudRendering path; return $task_vulkan_report."
fi

printf '\nVULKAN_DEVICE_READY\nNow rerun 03_smoke.sh. No dataset has been generated by this repair.\n'
